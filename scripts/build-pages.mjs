import assert from 'node:assert/strict';
import {cp, lstat, mkdir, readFile, rm, symlink, writeFile} from 'node:fs/promises';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {syncPDFAssets} from './sync-pdf-assets.mjs';
import {checkPagesArtifact} from './check-pages-deployment.mjs';

const root=fileURLToPath(new URL('../',import.meta.url));
// This directory is already excluded by both Git and the project's TypeScript config.
const stage=path.join(root,'work/github-pages-build');
const marker=path.join(stage,'.generated-pages-build');
const basePath=process.env.NEXT_PUBLIC_BASE_PATH??'/exam-grading-assistant';
assert(basePath===''||/^\/[A-Za-z0-9_-]+(?:\/[A-Za-z0-9_-]+)*$/.test(basePath),'Invalid Pages base path.');
try{
  await readFile(marker);
  await rm(stage,{recursive:true,force:true});
}catch(error){
  if(error.code!=='ENOENT')throw error;
  try{
    await lstat(stage);
    throw new Error('Refusing to replace an unmarked Pages build directory.');
  }catch(check){if(check.code!=='ENOENT')throw check;}
}
await mkdir(stage,{recursive:true});
await writeFile(marker,'Generated by scripts/build-pages.mjs; safe to rebuild.\n');
await syncPDFAssets();
// Only build inputs are copied. In particular no .env, Git metadata, uploads or results.
for(const name of ['app','components','hooks','lib','vendor','public','package.json','tsconfig.json','next.config.ts','postcss.config.mjs']){
  await cp(path.join(root,name),path.join(stage,name),{
    recursive:true,
    filter:source=>source!==path.join(root,'app/api'),
  });
}
await symlink(path.join(root,'node_modules'),path.join(stage,'node_modules'),'dir');
// The static build has no access to deployment credentials or public secret variables.
const buildEnv=Object.fromEntries(['PATH','HOME','USERPROFILE','SYSTEMROOT','WINDIR','TEMP','TMP','TMPDIR','CI','LANG','LC_ALL','TZ','FORCE_COLOR','NO_COLOR']
  .filter(name=>process.env[name]!==undefined).map(name=>[name,process.env[name]]));
Object.assign(buildEnv,{
  NODE_ENV:'production',NEXT_TELEMETRY_DISABLED:'1',
  NEXT_PUBLIC_DEPLOYMENT_TARGET:'github-pages',NEXT_PUBLIC_BASE_PATH:basePath,
});
await new Promise((resolve,reject)=>{
  const child=spawn(process.execPath,[path.join(root,'node_modules/next/dist/bin/next'),'build','--webpack'],{cwd:stage,env:buildEnv,stdio:'inherit'});
  child.once('error',reject);
  child.once('exit',(code,signal)=>code===0?resolve():reject(new Error(`Static build failed (${signal??code}).`)));
});
await writeFile(path.join(stage,'out/.nojekyll'),'');
await checkPagesArtifact(path.join(stage,'out'),basePath);
// Replace only the generated export after the new artifact has passed its checks.
await rm(path.join(root,'out'),{recursive:true,force:true});
await cp(path.join(stage,'out'),path.join(root,'out'),{recursive:true});
console.log(`GitHub Pages export ready: out/ (base path ${basePath||'/'}).`);
